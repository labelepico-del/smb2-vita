param(
    [Parameter(Mandatory = $true)][string]$Rom,
    [Parameter(Mandatory = $true)][string]$Output
)

$ErrorActionPreference = "Stop"

$romPath = (Resolve-Path $Rom).Path
$bytes = [System.IO.File]::ReadAllBytes($romPath)

if ($bytes.Length -lt 16 -or
    $bytes[0] -ne 0x4E -or $bytes[1] -ne 0x45 -or
    $bytes[2] -ne 0x53 -or $bytes[3] -ne 0x1A) {
    throw "$romPath is not an iNES image"
}

$mapper = (($bytes[6] -shr 4) -bor ($bytes[7] -band 0xF0))
$sha = [System.Security.Cryptography.SHA256]::Create()
$digest = -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString("x2") })

Write-Host "ROM: $romPath ($($bytes.Length) bytes, mapper $mapper)"
Write-Host "SHA-256: $digest"
if ($digest -eq "47ba60fad332fdea5ae44b7979fe1ee78de1d316ee027fea2ad5fe3c0d86f25a") {
    Write-Host "Verified against SMB2 PRG0."
} else {
    Write-Host "note: not the PRG0 hash; embedding anyway (a ROM hack or patched build)."
}

$outPath = [System.IO.Path]::GetFullPath($Output)
$outDir = [System.IO.Path]::GetDirectoryName($outPath)
if (-not (Test-Path $outDir)) {
    New-Item -ItemType Directory -Force -Path $outDir | Out-Null
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("// Generated by tools/embed_rom.ps1 -- do not edit.")
[void]$sb.AppendLine("// Source SHA-256: $digest")
[void]$sb.AppendLine('#include "rom_data.h"')
[void]$sb.AppendLine()
[void]$sb.AppendLine("const unsigned char smb2_rom[] = {")

for ($i = 0; $i -lt $bytes.Length; $i += 16) {
    $end = [Math]::Min($i + 16, $bytes.Length)
    $values = New-Object System.Collections.Generic.List[string]
    for ($j = $i; $j -lt $end; $j++) {
        $values.Add(("0x{0:X2}" -f $bytes[$j]))
    }
    $suffix = if ($end -lt $bytes.Length) { "," } else { "" }
    [void]$sb.AppendLine("    " + ($values -join ", ") + $suffix)
}

[void]$sb.AppendLine("};")
[void]$sb.AppendLine()
[void]$sb.AppendLine("const unsigned int smb2_rom_size = $($bytes.Length)u;")

[System.IO.File]::WriteAllText($outPath, $sb.ToString(), [System.Text.Encoding]::ASCII)
Write-Host "Wrote $outPath"
