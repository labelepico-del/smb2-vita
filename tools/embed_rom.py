#!/usr/bin/env python3
"""Convert a built .nes image into a C++ byte array for embedding in the VPK.

This intentionally lives outside CMake: the ROM is game data, not source.
CI builds the ROM from the Xkeeper0/smb2 disassembly immediately before
running this script.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import sys

PRG0_SHA256 = "47ba60fad332fdea5ae44b7979fe1ee78de1d316ee027fea2ad5fe3c0d86f25a"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rom", type=pathlib.Path, help="input .nes file")
    parser.add_argument("output", type=pathlib.Path, help="generated .cpp file")
    args = parser.parse_args()

    data = args.rom.read_bytes()
    if len(data) < 16 or data[:4] != b"NES\x1a":
        print(f"error: {args.rom} is not an iNES image", file=sys.stderr)
        return 1

    mapper = (data[6] >> 4) | (data[7] & 0xF0)
    digest = hashlib.sha256(data).hexdigest()
    print(f"ROM: {args.rom} ({len(data)} bytes, mapper {mapper})")
    print(f"SHA-256: {digest}")
    if digest == PRG0_SHA256:
        print("Verified against SMB2 PRG0.")
    else:
        print("note: not the PRG0 hash; embedding anyway (a ROM hack or patched build).")

    out = args.output
    out.parent.mkdir(parents=True, exist_ok=True)

    with out.open("w", encoding="ascii", newline="\n") as f:
        f.write("// Generated by tools/embed_rom.py -- do not edit.\n")
        f.write(f"// Source SHA-256: {digest}\n")
        f.write('#include "rom_data.h"\n\n')
        f.write("const unsigned char smb2_rom[] = {\n")
        for start in range(0, len(data), 16):
            chunk = data[start : start + 16]
            values = ", ".join(f"0x{byte:02X}" for byte in chunk)
            comma = "," if start + 16 < len(data) else ""
            f.write(f"    {values}{comma}\n")
        f.write("};\n\n")
        f.write(f"const unsigned int smb2_rom_size = {len(data)}u;\n")

    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
